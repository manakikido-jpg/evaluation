export const LATEST_CHANGE_ID = CHANGELOG[0]!.id;

/** その人が最後に読んだ id より新しいもの（読んだ記録がなければ全部） */
export function unseenChanges(seenId: string | undefined): ChangelogEntry[] {
  if (!seenId) return CHANGELOG;
  const i = CHANGELOG.findIndex((e) => e.id === seenId);
  return i < 0 ? CHANGELOG : CHANGELOG.slice(0, i);
}
